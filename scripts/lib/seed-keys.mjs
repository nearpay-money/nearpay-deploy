#!/usr/bin/env node
/**
 * Generates the local stack's TEST-ONLY secrets into nearpay-deploy/.secrets (git-ignored), never
 * overwriting an existing file (lld/platform.md §1 "Secrets"; ADR-0015). Nothing here is used in
 * live mode: live credentials (1Click key, Explorer token, treasury/relayer keys, RPC keys) are
 * added by the owner.
 *
 * Writes: database passwords and URLs, Ed25519 signing keys (JWT current/next, sentinel, payments
 * ticket, webhooks, sandbox), service client secrets (+ identity's hashed list), per-service KEKs,
 * the Turnstile test secret, the registry password, and public material under .secrets/public/
 * (keys.env for Compose, sentinel_keys.json for static builds).
 */
import { createHash, createPublicKey, generateKeyPairSync, randomBytes } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const dir = process.env.NP_SECRETS_DIR ?? join(root, ".secrets");

/** Services with a database and a service client (lld/platform.md §1, foundations §9). */
export const SERVICES = ["identity", "payments", "billing", "rails", "agentpay", "compliance", "webhooks", "notify", "sandbox", "sentinel"];
/** Cloudflare's documented always-pass Turnstile test secret (pairs with sitekey 1x00000000000000000000AA). */
const TURNSTILE_TEST_SECRET = "1x0000000000000000000000000000000AA";

const created = [];
const hex = (n) => randomBytes(n).toString("hex");

function put(name, content) {
  const path = join(dir, name);
  if (existsSync(path)) return readFileSync(path, "utf8");
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  writeFileSync(path, content);
  // Readable by the containers' non-root users (file secrets are bind mounts); .secrets itself is 0700.
  chmodSync(path, 0o644);
  created.push(name);
  return content;
}

function ed25519Pem() {
  return generateKeyPairSync("ed25519").privateKey.export({ type: "pkcs8", format: "pem" }).toString();
}

/** Raw 32-byte public key, base64url (the format of `SentinelKey.public_key` in the spec). */
function publicRaw(pem) {
  const jwk = createPublicKey(pem).export({ format: "jwk" });
  return jwk.x;
}

/** Stable key id from the public key: `local-` + 12 hex of its SHA-256 (spec kid pattern ^[a-z0-9-]{1,64}$). */
function kidOf(pem) {
  return `local-${createHash("sha256").update(Buffer.from(publicRaw(pem), "base64url")).digest("hex").slice(0, 12)}`;
}

mkdirSync(dir, { recursive: true, mode: 0o700 });
chmodSync(dir, 0o700);

put("postgres_password", hex(24));
put("registry_password", hex(24));
for (const svc of SERVICES) {
  put(`db_url_${svc}`, `postgres://${svc}_app:${hex(24)}@postgres:5432/${svc}`);
  put(`db_migrate_url_${svc}`, `postgres://${svc}_migrator:${hex(24)}@postgres:5432/${svc}`);
  put(`kek_${svc}`, randomBytes(32).toString("base64"));
}
put("db_registry_url_sentinel", `postgres://sentinel_ro:${hex(24)}@postgres:5432/identity`);

const jwtCurrent = put("jwt/current.pem", ed25519Pem());
put("jwt/next.pem", ed25519Pem());
const sentinel = put("sentinel_signing_key.pem", ed25519Pem());
const ticket = put("payments_ticket_key.pem", ed25519Pem());
const webhook = put("webhook_signing_key.pem", ed25519Pem());
const sandbox = put("sandbox_signing_key.pem", ed25519Pem());
put("turnstile_secret", TURNSTILE_TEST_SECRET);

const clients = {};
for (const svc of SERVICES) {
  const secret = put(`service_client_${svc}`, hex(32)).trim();
  clients[svc] = createHash("sha256").update(secret).digest("hex");
}
// Identity's view: client id → SHA-256 of the secret (scopes are static per spec SERVICE_CLIENT_SCOPES).
// Rewritten when it no longer matches the individual secrets (e.g. one was deleted to rotate it).
const clientsDoc = `${JSON.stringify({ clients: SERVICES.map((id) => ({ client_id: id, secret_sha256: clients[id] })) }, null, 2)}\n`;
const clientsPath = join(dir, "service_clients.json");
if (!existsSync(clientsPath) || readFileSync(clientsPath, "utf8") !== clientsDoc) {
  writeFileSync(clientsPath, clientsDoc);
  chmodSync(clientsPath, 0o644);
  created.push("service_clients.json");
}

// Public material: always regenerated from the private keys (never secret).
const sentinelKid = kidOf(sentinel);
const publicEnv = [
  "# Generated by scripts/seed.sh keys from the local test keys. Public values only.",
  `NP_SENTINEL_KID=${sentinelKid}`,
  `NP_JWT_CURRENT_KID=${kidOf(jwtCurrent)}`,
  `NP_PAYMENTS_TICKET_PUBKEY=${publicRaw(ticket)}`,
  `NP_SANDBOX_SIGNING_PUBKEY=${publicRaw(sandbox)}`,
  `NP_WEBHOOK_SIGNING_KID=${kidOf(webhook)}`,
  "",
].join("\n");
mkdirSync(join(dir, "public"), { recursive: true });
writeFileSync(join(dir, "public", "keys.env"), publicEnv);
writeFileSync(join(dir, "public", "sentinel_keys.json"), `${JSON.stringify([{ kid: sentinelKid, public_key: publicRaw(sentinel) }])}\n`);

console.log(created.length ? `created ${created.length} secret file(s) in ${dir}` : `secrets up to date in ${dir}`);
