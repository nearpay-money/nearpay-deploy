#!/usr/bin/env node
// Generates compose/traefik/dynamic/ops.yaml — the console host's API routers — from the spec's OPS_ROUTES
// (lld/platform.md §1 "Traefik routing", lld/dashboard-and-console.md §2).
//
//   node scripts/lib/ops-routes.mjs [<@nearpay-internal/spec entry>] > compose/traefik/dynamic/ops.yaml
//   node scripts/lib/ops-routes.mjs --check [<entry>]     exits 1 when the committed file differs
//
// The entry defaults to ../nearpay-spec/packages/spec-internal/dist/internal-entry.js (a built spec checkout).
//
// Routing model: the console calls `ops.<domain>/api/ops/…` same-origin; `/api` is stripped and every request passes
// ForwardAuth (identity authorizes the ops cookie; the anonymous sign-in routes are spec OPS_ANONYMOUS_ROUTES).
// Each `/ops/<segment>` prefix goes to the service that owns most of its routes; routes under that prefix owned by
// another service (e.g. `/ops/merchants/{id}/suspension*` → compliance) get exact-path routers at a higher priority.
// GET routers are not access-logged: Traefik logs the full request URI and cannot drop only the query string, and
// console list queries can carry personal data (listOpsMerchants `q` = member email). Writes carry no query strings
// (bodies are never logged) and stay in the access log; every console write is also audited by its service.
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const deploy = resolve(here, "../..");
const target = join(deploy, "compose/traefik/dynamic/ops.yaml");

const args = process.argv.slice(2);
const check = args.includes("--check");
const entry = resolve(
  args.find((a) => !a.startsWith("--")) ?? join(deploy, "../nearpay-spec/packages/spec-internal/dist/internal-entry.js"),
);

const spec = await import(pathToFileURL(entry).href);
const routes = spec.OPS_ROUTES;
const anonymous = spec.OPS_ANONYMOUS_ROUTES;
if (!Array.isArray(routes) || routes.length === 0) throw new Error(`${entry}: no OPS_ROUTES`);
const version = JSON.parse(readFileSync(join(dirname(entry), "../package.json"), "utf8")).version;

const prefixOf = (path) => path.split("/").slice(0, 3).join("/"); // /ops/<segment>
const regexOf = (path) => `^/api${path.replace(/\{[a-z_]+\}/g, "[^/]+")}$`;
const isAnon = (r) => anonymous.some((a) => a.method === r.method && a.path === r.path);

// prefix → owning service: the owner of the prefix's shortest route (the collection itself, e.g. GET /ops/merchants →
// identity); ties broken by route count, then name, for a stable output
const depth = (path) => path.split("/").length;
const owners = new Map();
for (const p of new Set(routes.map((r) => prefixOf(r.path)))) {
  const under = routes.filter((r) => prefixOf(r.path) === p);
  const min = Math.min(...under.map((r) => depth(r.path)));
  const count = new Map();
  for (const r of under) if (depth(r.path) === min) count.set(r.service, (count.get(r.service) ?? 0) + 1);
  owners.set(p, [...count].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0][0]);
}

const services = [...new Set(routes.map((r) => r.service))].sort();
const lines = [];
const out = (s = "") => lines.push(s);
const host = "Host(`ops.{{ $d }}`)";
const mw = "[ops-local-only, strip-internal-headers, api-prefix, authz, api-headers]";

out(`# GENERATED by scripts/lib/ops-routes.mjs from @nearpay-internal/spec ${version} OPS_ROUTES — do not edit by hand.`);
out("# Console host API routers (lld/platform.md §1): ops.<domain>/api/ops/* → owning service, ForwardAuth (ops cookie).");
out("# GET routers are not access-logged (query strings may carry personal data; see the generator's header).");
out('{{- $d := env "NP_BASE_DOMAIN" }}');
out("http:");
out("  routers:");

const router = (name, rule, priority, service, opts = {}) => {
  out(`    ${name}:`);
  out("      entryPoints: [websecure]");
  out(`      rule: '${rule}'`);
  out(`      priority: ${priority}`);
  out(`      middlewares: ${opts.middlewares ?? mw}`);
  out(`      service: ${service}`);
  if (opts.quiet) out("      observability: { accessLogs: false }");
};
const pathOr = (prefixes) =>
  prefixes.map((p) => `Path(\`/api${p}\`) || PathPrefix(\`/api${p}/\`)`).join(" || ");

// 1. anonymous sign-in routes: exact method + path, rate-limited per client IP
const anon = routes.filter(isAnon).sort((a, b) => a.path.localeCompare(b.path));
for (const r of anon) if (r.service !== "identity") throw new Error(`anonymous ops route ${r.id} is not identity's`);
router(
  "ops-auth-anonymous",
  `${host} && Method(\`POST\`) && (${anon.map((r) => `Path(\`/api${r.path}\`)`).join(" || ")})`,
  300,
  "identity",
  { middlewares: "[ops-local-only, ops-auth-ratelimit, strip-internal-headers, api-prefix, authz, api-headers]" },
);

// 2. routes owned by another service than their prefix: exact paths
for (const svc of services) {
  const odd = routes.filter((r) => r.service === svc && owners.get(prefixOf(r.path)) !== svc && !isAnon(r));
  for (const [kind, sel] of [
    ["read", (r) => r.method === "GET"],
    ["write", (r) => r.method !== "GET"],
  ]) {
    const rs = odd.filter(sel);
    if (!rs.length) continue;
    const paths = [...new Set(rs.map((r) => r.path))].sort();
    const methods = kind === "read" ? "Method(`GET`)" : `(${[...new Set(rs.map((r) => r.method))].sort().map((m) => `Method(\`${m}\`)`).join(" || ")})`;
    router(
      `ops-${svc}-exact-${kind}`,
      `${host} && ${methods} && (${paths.map((p) => `PathRegexp(\`${regexOf(p)}\`)`).join(" || ")})`,
      200,
      svc,
      { quiet: kind === "read" },
    );
  }
}

// 3. prefixes per owning service
for (const svc of services) {
  const prefixes = [...owners].filter(([, s]) => s === svc).map(([p]) => p).sort();
  if (!prefixes.length) continue;
  router(`ops-${svc}-read`, `${host} && Method(\`GET\`) && (${pathOr(prefixes)})`, 100, svc, { quiet: true });
  router(`ops-${svc}-write`, `${host} && !Method(\`GET\`) && (${pathOr(prefixes)})`, 100, svc);
}

out("");
out("# Route table this file was generated from (method path → service):");
for (const r of [...routes].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method)))
  out(`#   ${r.method.padEnd(4)} ${r.path} → ${r.service}${isAnon(r) ? " (anonymous)" : ""}`);

const text = `${lines.join("\n")}\n`;
if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== text) {
    process.stderr.write(`ops-routes: ${target} is out of date (regenerate with scripts/lib/ops-routes.mjs)\n`);
    process.exit(1);
  }
  process.stdout.write("ops-routes: up to date\n");
} else {
  process.stdout.write(text);
}
